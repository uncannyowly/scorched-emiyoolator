/*
 * The emulated PC around the game's code: run loops, interrupts, time,
 * ports and the devices (PIC, PIT/speaker, keyboard, VGA, mouse, DOS, BIOS).
 */
#ifndef MACHINE_H
#define MACHINE_H

#include "cpu.h"
#include "insn.h"

#include <stdio.h>

/* fake ROM segments */
#define BIOS_SEG 0xF000   /* HLE entry points: interrupt vectors, VESA window function */
#define VBIOS_SEG 0xC000  /* VESA info blocks, fonts */

/* where DOS loads the program (the PSP) */
#define PSP_SEG 0x0100
#define LOAD_SEG (PSP_SEG + 0x10)

/* ---- configuration ------------------------------------------------------------ */

typedef struct {
	int realtime;          /* 1: follow the host clock; 0: virtual time from icount */
	double mips;           /* virtual CPU speed in deterministic mode */
	int no_compiled;       /* run everything in the interpreter */
	int trace;             /* debug: log instructions */
	int log_io;            /* debug: log port accesses to unknown ports */
	const char *game_dir;  /* folder with SCORCH.EXE and its files ("C:\") */
	const char *exe;       /* path of SCORCH.EXE */
	const char *args;      /* command tail */
	int headless;          /* no window/panel */
	uint64_t max_ms;       /* stop after this much (virtual or real) time; 0 = never */
	int fps;               /* frames presented per second (0: 60) */
} MachineConfig;

extern MachineConfig mcfg;
extern FILE *log_file;

void logf_(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
#define LOG(...) logf_(__VA_ARGS__)

/* ---- execution -------------------------------------------------------------------- */

typedef void (*CompiledFn)(void);

/* generated by the recompiler (or a stub returning NULL) */
CompiledFn compiled_lookup(uint16_t cs, uint16_t ip);
void compiled_init(void);
void compiled_disable(void);
extern const char *compiled_info;
extern const uint32_t compiled_image_sum; /* 0 if no compiled code */

/* addresses the interpreter had to run (written at exit, read by the recompiler) */
void uncompiled_note(uint16_t cs, uint16_t ip);
void uncompiled_write(const char *path);
extern int interp_xfer_kind; /* last transfer: 0 jump/none, 1 call/int/far, 2 return */

void machine_init(void);
void machine_run(void);
void machine_exit(int code) __attribute__((noreturn));

/* execute until CS:IP = (cs, ip) with SS:SP at or above sp_min */
void run_until(uint16_t cs, uint16_t ip, uint16_t sp_min);

/* one interpreted instruction; returns 1 if it transferred control */
int interp_step(void);

/* raise interrupt n now (push FLAGS, CS, ret_ip; jump to the vector) */
void cpu_interrupt(int n, uint16_t ret_ip);

/* compiled code: an INT instruction / an indirect or unknown call */
void compiled_int(int n, uint16_t ret_ip);
void compiled_call_far(uint16_t cs, uint16_t ip, uint16_t ret_cs, uint16_t ret_ip);
/* compiled code: periodic check at backward branches (icount >= deadline) */
void compiled_checkpoint(uint16_t resume_ip);

/* events: polls the host / raises due interrupts / presents frames. For the
 * interpreter it may push an interrupt frame and change CS:IP. */
void machine_event(void);

/* ---- time ------------------------------------------------------------------------- */

uint64_t time_us(void);      /* emulated microseconds since start */
uint64_t time_ns(void);
void time_sleep_until_us(uint64_t t); /* real-time mode: wait; virtual: advance */
extern uint64_t sleep_step_us;  /* real time: what a short sleep really takes (0: virtual) */

/* ---- interrupts ----------------------------------------------------------------- */

void pic_raise(int irq);
void pic_lower(int irq);
int pic_pending(void);    /* an unmasked IRQ can be delivered */

/* ---- ports ----------------------------------------------------------------------- */

typedef uint8_t (*PortIn)(uint16_t port);
typedef void (*PortOut)(uint16_t port, uint8_t v);
void port_register(uint16_t first, uint16_t last, PortIn in, PortOut out);

/* ---- devices ----------------------------------------------------------------------- */

void bios_init(void);
void bios_dispatch(void);  /* CS == BIOS_SEG: run the HLE routine at IP */
void bios_tick(void);

int dos_load(const char *exe, const char *args);
uint32_t dos_image_checksum(void);
void dos_int21(void);
void dos_shutdown(void);

void pit_init(void);
uint64_t pit_next_irq_us(void);
void pit_update(uint64_t now);
void pit_update_slept(uint64_t now);
void speaker_render(int16_t *out, int frames, int rate);

void kbd_init(void);
void kbd_key(int scancode, int down);  /* queue a make/break (with E0 prefix if needed) */
int kbd_bios_read(int peek, int extended, uint16_t *key); /* INT 16h */
void kbd_bios_int9(void);
uint8_t kbd_shift_flags(void);

/* a picture of the screen: palette indices, for rendering elsewhere */
#define PIC_MAX (1024 * 768)
typedef struct {
	uint8_t *pic; /* PIC_MAX bytes */
	uint32_t pal[256];
	int sw, sh;
	uint8_t mask;
} Picture;
void vga_snapshot(Picture *p);
void vga_render_picture(const Picture *p, uint32_t *dst, int w, int h, int pitch);

void vga_init(void);
void vga_int10(void);
int vga_present_due(uint64_t now);
int vga_update_picture(void);
void vga_render(uint32_t *dst, int w, int h, int pitch);
int vga_mode_width(void);
int vga_mode_height(void);
uint64_t vga_frame_counter(void);
void vesa_window_call(void);

void mouse_init(void);
void mouse_int33(void);
void mouse_move(int dx, int dy);        /* relative motion in mickeys */
void mouse_set_pos(int x, int y);       /* absolute, in screen pixels */
void mouse_buttons(int mask);
void mouse_get_screen_pos(int *x, int *y, int *visible);
void mouse_event_return(void);

/* frontend (main.c): poll host input, present frames */
void frontend_frame(void);
void frontend_poll(void);

#endif
